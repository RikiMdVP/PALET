# Exporta papers a formato BibTeX

import pandas as pd
import sys
import os


def generate_bibtex_entry(paper: pd.Series, entry_id: str) -> str:
    """Genera entrada BibTeX para un paper."""

    # Tipo de entrada
    entry_type = "article"  # Podría mejorarse según paper type

    # Campos requeridos
    title = paper.get('title', 'Untitled').replace('{', '').replace('}', '')

    # Autores
    authors = paper.get('authors', 'Unknown')
    if authors and authors != 'Unknown':
        # Convertir "Smith, J.; Doe, A." a formato BibTeX
        author_list = authors.split(';')
        authors_bibtex = ' and '.join([a.strip() for a in author_list])
    else:
        authors_bibtex = 'Unknown'

    # Año
    year = paper.get('year')
    year_str = str(int(year)) if pd.notna(year) else 'n.d.'

    # Journal/Source
    journal = paper.get('source', '')

    # DOI
    doi = paper.get('doi', '')

    # Abstract
    abstract = paper.get('abstract', '')

    # URL
    url = paper.get('url', '')

    # Construir entrada
    bibtex = f"@{entry_type}{{{entry_id},\n"
    bibtex += f"  author = {{{authors_bibtex}}},\n"
    bibtex += f"  title = {{{title}}},\n"

    if journal:
        bibtex += f"  journal = {{{journal}}},\n"

    bibtex += f"  year = {{{year_str}}},\n"

    if doi:
        bibtex += f"  doi = {{{doi}}},\n"

    if url:
        bibtex += f"  url = {{{url}}},\n"

    # Validar que abstract sea string antes de limpiar
    if abstract and isinstance(abstract, str):  # ← AÑADIR isinstance()
        abstract_clean = abstract.replace('{', '').replace('}', '')
        bibtex += f"  abstract = {{{abstract_clean}}},\n"

    bibtex += "}\n"

    return bibtex


def export_to_bibtex(csv_path: str, output_path: str) -> str:
    """Exporta CSV de papers a BibTeX."""

    df = pd.read_csv(csv_path)

    bibtex_content = "% BibTeX generated by PALET\n"
    bibtex_content += f"% Total entries: {len(df)}\n\n"

    for idx, paper in df.iterrows():
        # Generar entry_id único
        first_author = paper.get('authors', 'unknown').split(';')[0].split(',')[0].strip()
        year = paper.get('year')
        year_str = str(int(year)) if pd.notna(year) else 'nd'

        entry_id = f"{first_author.lower().replace(' ', '_')}_{year_str}_{idx}"

        bibtex_content += generate_bibtex_entry(paper, entry_id)
        bibtex_content += "\n"

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(bibtex_content)

    print(f"✓ BibTeX exportado: {output_path}")
    print(f"  Entradas: {len(df)}")

    return output_path


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Uso: python export_bibtex.py <csv_path> [output_path]")
        sys.exit(1)

    csv_path = sys.argv[1]

    if len(sys.argv) > 2:
        output_path = sys.argv[2]
    else:
        output_path = csv_path.replace('.csv', '.bib')

    export_to_bibtex(csv_path, output_path)
